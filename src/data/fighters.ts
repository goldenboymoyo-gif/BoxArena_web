export function getFighter(id: string): Fighter | undefined {
  return fighters.find((f) => f.id === id);
}

export function getFighterByName(name: string): Fighter | undefined {
  const normalized = name.toLowerCase().replace(/[^a-z]/g, "");
  return fighters.find(
    (f) => f.name.toLowerCase().replace(/[^a-z]/g, "") === normalized
  );
}

